export const NATIONWIDE = Object.keys(REGIONS);

export function resolveRegions(input) {
  if (!input || input === '전국' || input === 'nationwide') return NATIONWIDE;
  const names = input.split(',').map((s) => s.trim()).filter(Boolean);
  const missing = names.filter((n) => !REGIONS[n]);
  if (missing.length > 0) {
    throw new Error(`알 수 없는 지역: ${missing.join(', ')} (가능: ${NATIONWIDE.join(', ')}, 전국)`);
  }
  return names;
}
